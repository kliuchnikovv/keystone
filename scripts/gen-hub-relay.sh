#!/usr/bin/env bash
# Give a hub a relay of its own: an id on that relay and the secret it uses there.
#
# The secret is derived from the relay's master key, the same way the relay
# derives it: HMAC-SHA256(master, "hub:<id>"). So adding a home is this script
# and a flash - nothing has to be added to the relay's configuration, and no
# redeploy happens.
#
# The master key comes from RELAY_MASTER_SECRET: the environment first, then the
# .env file in the root of the repository (the same one the relay reads on the
# server). It never leaves this machine and never goes into git.
#
#   scripts/gen-hub-relay.sh [--id <hub-id>] [--relay <host>] [--force]
#
# The hub dials wss://<host>/tunnel/<id>; the app talks to wss://<host>/client/<id>.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIR="${ROOT}/firmware/brain-s3/main"
OUT="${DIR}/relay_identity.h"

HOST="keystone-esp-production.up.railway.app"
ID=""
FORCE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --id) ID="${2:-}"; shift 2 ;;
    --relay) HOST="${2:-}"; shift 2 ;;
    --force) FORCE=1; shift ;;
    *) echo "usage: scripts/gen-hub-relay.sh [--id <hub-id>] [--relay <host>] [--force]" >&2; exit 2 ;;
  esac
done

if [[ -e "$OUT" && $FORCE -eq 0 ]]; then
  echo "This hub already has a relay identity (${OUT})." >&2
  echo "Re-running gives the hub a new id, and the old one stops working." >&2
  echo "Pass --force if you mean it." >&2
  exit 1
fi

# The master key: the environment, then the .env file in the root of the repo.
MASTER="${RELAY_MASTER_SECRET:-}"
if [[ -z "$MASTER" && -f "${ROOT}/.env" ]]; then
  MASTER="$(sed -n 's/^[[:space:]]*RELAY_MASTER_SECRET[[:space:]]*=[[:space:]]*//p' "${ROOT}/.env" | tail -1)"
  MASTER="${MASTER%\"}"; MASTER="${MASTER#\"}"
  MASTER="${MASTER%\'}"; MASTER="${#MASTER#\'}"
fi
if [[ -z "$MASTER" ]]; then
  echo "No RELAY_MASTER_SECRET." >&2
  echo "Put it in ${ROOT}/.env (RELAY_MASTER_SECRET=...) or in the environment." >&2
  echo "It must be the same key the relay uses - otherwise the hub cannot register." >&2
  exit 1
fi

# The id: short, boring, and safe in a URL.
make_id() {
  local c=""
  while [[ ${#c} -lt 8 ]]; do
    c+="$(head -c 64 /dev/urandom | LC_ALL=C tr -dc 'abcdefghijkmnopqrstuvwxyz23456789' | head -c $((8 - ${#c})))"
  done
  echo "hub-$c"
}

# The secret: the same derivation the relay does. The relay derives it from the
# same master key, so the hub can be added without touching the relay.
derive_secret() {
  printf 'hub:%s' "$1" | openssl dgst -sha256 -hmac "$MASTER" | awk '{print $NF}'
}

umask 077
[[ -n "$ID" ]] || ID="$(make_id)"
SECRET="$(derive_secret "$ID")"

{
  echo "// Generated by scripts/gen-hub-relay.sh. NOT for git: it holds the hub's secret for the relay."
  echo "#define KEYSTONE_RELAY_HOST \"${HOST}\""
  echo "#define KEYSTONE_RELAY_ID \"${ID}\""
  echo "#define KEYSTONE_RELAY_SECRET \"${SECRET}\""
} > "$OUT"
chmod 600 "$OUT"

echo "Wrote ${OUT}"
echo
echo "The hub id is ${ID} and its secret is derived from the master key."
echo "Nothing has to be added to the relay: it derives the same secret itself."
echo
echo "The hub dials wss://${HOST}/tunnel/${ID} on its own."
echo "The app talks to wss://${HOST}/client/${ID}."
echo
echo "Flash the hub with this identity, and it will register on its own."
