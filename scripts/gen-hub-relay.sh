#!/usr/bin/env bash
# Give a hub a relay of its own: an id on that relay and a secret only this hub knows.
#
# The secret is written into the firmware (firmware/brain-s3/main/relay_identity.h,
# gitignored) and the same pair goes into the relay's environment
# (RELAY_HUB_SECRETS="id:secret"). So the person who receives the box never types
# a secret, the hub registers with the relay by itself, and nobody else can
# register a tunnel under this hub's id.
#
#   scripts/gen-hub-relay.sh [--id <hub-id>] [--relay <host>] [--force]
#
# The hub dials wss://<host>/tunnel/<id>; the app talks to wss://<host>/client/<id>.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/firmware/brain-s3/main"
OUT="${DIR}/relay_identity.h"

HOST="keystone-esp-production.up.railway.app"
ID=""
FORCE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --id) ID="${2:-}"; shift 2 ;;
    --relay) HOST="${2:-}"; shift 2 ;;
    --force) FORCE=1; shift ;;
    *) echo "usage: scripts/gen-hub-relay.sh [--id <hub-id>] [--relay <host>] [--force]" >&2; exit 2 ;;
  esac
done

if [[ -e "$OUT" && $FORCE -eq 0 ]]; then
  echo "This hub already has a relay identity (${OUT})." >&2
  echo "Re-running gives the hub a new id and secret, and the relay has to be told about it." >&2
  echo "Pass --force if you mean it." >&2
  exit 1
fi

# The id: short, boring, and safe in a URL.
make_id() {
  local c=""
  while [[ ${#c} -lt 8 ]]; do
    c+="$(head -c 64 /dev/urandom | LC_ALL=C tr -dc 'abcdefghijkmnopqrstuvwxyz23456789' | head -c $((8 - ${#c})))"
  done
  echo "hub-$c"
}

# The secret: 48 characters, nothing a person has to type.
make_secret() {
  head -c 96 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9' | head -c 48
}

umask 077
[[ -n "$ID" ]] || ID="$(make_id)"
SECRET="$(make_secret)"

{
  echo "// Generated by scripts/gen-hub-relay.sh. NOT for git: it holds the hub's secret for the relay."
  echo "#define KEYSTONE_RELAY_HOST \"${HOST}\""
  echo "#define KEYSTONE_RELAY_ID \"${ID}\""
  echo "#define KEYSTONE_RELAY_SECRET \"${SECRET}\""
} > "$OUT"
chmod 600 "$OUT"

echo "Wrote ${OUT}"
echo
echo "The relay has to know this hub. Put this in its environment (on Railway: the service's variables):"
echo
echo "  RELAY_HUB_SECRETS=${ID}:${SECRET}"
echo
echo "More hubs? One value for all of them, separated by commas:"
echo "  RELAY_HUB_SECRETS=${ID}:${SECRET},other-id:other-secret"
echo
echo "The hub dials wss://${HOST}/tunnel/${ID} on its own."
echo "The app talks to wss://${HOST}/client/${ID}."
