#!/usr/bin/env bash
# Generate the hub's own TLS identity: an ECDSA P-256 key and a self-signed certificate,
# written to firmware/brain-s3/main/hub_cert.pem and hub_key.pem and compiled into the
# firmware through the generated hub_identity.cpp (all three are gitignored). One identity per device: the private key
# never enters git, and the app pins the certificate's SHA-256 fingerprint
# (docs/app-protocol.md §10). Re-running REPLACES the identity, so every app that pinned
# the old fingerprint must be told the new one.
#
#   scripts/gen-hub-cert.sh [--force] [extra-SAN ...]      e.g.  scripts/gen-hub-cert.sh DNS:hub.example.org IP:192.168.0.202
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/firmware/brain-s3/main"
CERT="${DIR}/hub_cert.pem"
KEY="${DIR}/hub_key.pem"
SRC="${DIR}/hub_identity.cpp"

FORCE=0
SANS=("DNS:keystone-hub.local" "DNS:keystone-hub")
for a in "$@"; do
  if [[ "$a" == "--force" ]]; then FORCE=1; else SANS+=("$a"); fi
done

if [[ -e "$KEY" && $FORCE -eq 0 ]]; then
  echo "A hub identity already exists (${KEY})." >&2
  echo "Re-running would invalidate every pinned fingerprint; pass --force if you mean it." >&2
  exit 1
fi

SAN_LIST="$(IFS=,; echo "${SANS[*]}")"
umask 077
openssl ecparam -name prime256v1 -genkey -noout -out "$KEY"
openssl req -new -x509 -key "$KEY" -sha256 -days 3650 -out "$CERT" \
  -subj "/O=Keystone/CN=keystone-hub" \
  -addext "subjectAltName=${SAN_LIST}" \
  -addext "keyUsage=critical,digitalSignature" \
  -addext "extendedKeyUsage=serverAuth"
chmod 600 "$KEY"

# The firmware embeds the PEMs as string literals (works the same with PlatformIO and idf.py).
{
  echo "// Generated by scripts/gen-hub-cert.sh. NOT for git: it contains the hub's private key."
  echo "#include <cstddef>"
  echo "extern const char kHubCertPem[] = R\"PEM($(cat "$CERT")"
  echo ")PEM\";"
  echo "extern const std::size_t kHubCertPemLen = sizeof(kHubCertPem);"
  echo "extern const char kHubKeyPem[] = R\"PEM($(cat "$KEY")"
  echo ")PEM\";"
  echo "extern const std::size_t kHubKeyPemLen = sizeof(kHubKeyPem);"
} > "$SRC"
chmod 600 "$SRC"

echo "Wrote ${CERT}"
echo "Wrote ${KEY}  (keep it private; it is in .gitignore)"
echo "Wrote ${SRC}"
echo "SHA-256 fingerprint (what the app pins):"
openssl x509 -in "$CERT" -noout -fingerprint -sha256 | sed 's/^.*=//'
echo "Subject alternative names: ${SAN_LIST}"
