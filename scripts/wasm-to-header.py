#!/usr/bin/env python3
"""Turn a .wasm file into a C++ `constexpr uint8_t[]` header.

The firmware cannot read a file from disk at runtime yet (the LittleFS
`plugins` partition is a separate piece of work, design §5.6), so the
bundled test plugin is linked into the image as a byte array.

Usage:
    python3 scripts/wasm-to-header.py <in.wasm> <out.h> <symbol>

The symbol lands in namespace wasm_host.
"""
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    symbol = sys.argv[3]
    data = src.read_bytes()

    lines = [
        "// Auto-generated by scripts/wasm-to-header.py. Do not edit.",
        f"// Source: {src.name} ({len(data)} bytes)",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace wasm_host {",
        "",
        f"inline constexpr std::size_t {symbol}Len = {len(data)};",
        "",
        f"inline constexpr std::uint8_t {symbol}[] = {{",
    ]
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines += [
        "};",
        "",
        "}  // namespace wasm_host",
        "",
    ]
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(lines))
    print(f"wrote {dst} ({len(data)} B -> {symbol}[])")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
